/** Generate the ready-to-serve Italian page from the bilingual source.
 * Run: node scripts/build-fiat500l-locales.mjs [--check]
 * No packages are required. Never edit the generated Italian file directly.
 */
import { readFile, writeFile } from 'node:fs/promises';
import { fileURLToPath } from 'node:url';
const source = new URL('../fiat500l-wiki.html', import.meta.url);
const output = new URL('../fiat500l-wiki-it.html', import.meta.url);
const original = await readFile(source, 'utf8');
let html = original;
const attributes = tag => Object.fromEntries([...tag.matchAll(/([\w:-]+)="([^"]*)"/g)].map(match => [match[1], match[2]]));
// Fail before generating if an edit would ship an incomplete translation.
const ids = [...html.matchAll(/(?<![\w-])id="([^"]+)"/g)].map(match => match[1]);
if (new Set(ids).size !== ids.length) throw new Error('Duplicate guide IDs would break bookmarks.');
const cards = [...html.matchAll(/<details\b[^>]*class="guide-card"[\s\S]*?<\/details>/g)].map(match => match[0]);
if (!cards.length) throw new Error('The source has no guide sections.');
for (const card of cards) {
  const id = attributes(card.slice(0, card.indexOf('>') + 1)).id;
  const summary = card.match(/<summary\b[\s\S]*?<\/summary>/)?.[0] || '';
  for (const locale of ['en', 'it']) {
    if (!summary.includes(`data-ui-language="${locale}"`) || !card.includes(`data-language="${locale}"`)) {
      throw new Error(`Missing ${locale} heading or body in ${id}.`);
    }
  }
}
const indexStart = '<!-- GUIDE_PROCEDURE_INDEX_START -->';
const indexEnd = '<!-- GUIDE_PROCEDURE_INDEX_END -->';
if (!html.includes(indexStart) || !html.includes(indexEnd)) throw new Error('Missing procedure index markers.');
const indexLinks = cards.map(card => {
  const id = attributes(card.slice(0, card.indexOf('>') + 1)).id;
  const heading = card.match(/<h3\b[^>]*>([\s\S]*?)<\/h3>/)?.[1];
  return `<li><a href="#${id}">${heading}</a></li>`;
}).join('\n');
const procedureIndex = `${indexStart}
<details class="procedure-index">
<summary><span class="ui-copy" data-ui-language="en" lang="en">Browse all ${cards.length} procedures and reference sections</span><span class="ui-copy" data-ui-language="it" lang="it">Sfoglia tutte le ${cards.length} procedure e sezioni di riferimento</span></summary>
<nav aria-label="All guide sections" data-aria-label-en="All guide sections" data-aria-label-it="Tutte le sezioni della guida"><ul>
${indexLinks}
</ul></nav></details>
${indexEnd}`;
html = html.replace(/<!-- GUIDE_PROCEDURE_INDEX_START -->[\s\S]*?<!-- GUIDE_PROCEDURE_INDEX_END -->/, procedureIndex);
for (const match of html.matchAll(/<[a-z][^>]*data-(?:aria-label|placeholder|content|title|alt)-en="[^"]*"[^>]*>/g)) {
  const attrs = attributes(match[0]);
  for (const name of Object.keys(attrs).filter(name => /^data-.+-en$/.test(name))) {
    if (!attrs[name.replace(/-en$/, '-it')]) throw new Error(`Missing Italian attribute for ${name}.`);
  }
}
function italianAttributes(tag) {
  const attrs = attributes(tag);
  for (const attr of ['aria-label', 'placeholder', 'title', 'content', 'alt']) {
    if (attrs[`data-${attr}-it`]) tag = tag.replace(new RegExp(`(?<![\\w-])${attr}="[^"]*"`), `${attr}="${attrs[`data-${attr}-it`]}"`);
  }
  return tag;
}
let italian = html.replace(/<[a-z][^>]*>/g, italianAttributes)
  .replace(/<html\b[^>]*>/, '<html data-reading-language="it" data-ui-language="it" lang="it">')
  .replace(/(<title\b[^>]*>)[^<]*(<\/title>)/, (match, open, close) => open + attributes(open)['data-title-it'] + close)
  .replace('https://romitagl.com/fiat500l-wiki.html" rel="canonical"', 'https://romitagl.com/fiat500l-wiki-it.html" rel="canonical"')
  .replace(/(<meta content=")https:\/\/romitagl.com\/fiat500l-wiki.html(" property="og:url"\/?>)/, '$1https://romitagl.com/fiat500l-wiki-it.html$2')
  .replace(/(<meta content=")en_GB(" property="og:locale"\/?>)/, '$1it_IT$2')
  .replace(/(<a\b[^>]*data-language-choice="en"[^>]*>)/, match => match.replace(/ aria-current="true"/, ''))
  .replace(/(<a\b[^>]*data-language-choice="it"[^>]*)(>)/, '$1 aria-current="true"$2');
italian = '<!-- Generated by scripts/build-fiat500l-locales.mjs; edit fiat500l-wiki.html. -->\n' + italian;
if (process.argv.includes('--check')) {
  if (original !== html) throw new Error('Procedure index is stale. Run node scripts/build-fiat500l-locales.mjs.');
  if (await readFile(output, 'utf8') !== italian) throw new Error('Italian page is stale. Run node scripts/build-fiat500l-locales.mjs.');
  console.log('PASS: Italian page matches the bilingual source.');
} else {
  if (original !== html) await writeFile(source, html);
  await writeFile(output, italian);
  console.log(`Generated ${fileURLToPath(output)}`);
}
